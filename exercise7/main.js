

let colors = ["Red", "blue", "green", "yellow"]

console.log(colors);
console.log("after shift")
colors.shift("")
console.log(colors)

console.log(colors);
console.log("after unshift")
colors.unshift("Red")
console.log(colors)

console.log(colors);
console.log("after push")
colors.push("green")
console.log(colors)

console.log(colors);
console.log("after pop")
colors.pop("")
console.log(colors)
